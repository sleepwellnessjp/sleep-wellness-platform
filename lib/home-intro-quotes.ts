const LAST_KEY = "swij-intro-quote-last";

/**
 * 前回と異なる格言を 1 つ選ぶ。
 * localStorage に直近の index を保存し、連続で同じものを避ける。
 * SSR とクライアントで結果が変わらないよう、必ずクライアント（useEffect 内）で呼ぶこと。
 */
export function pickMaNoShoQuote(): string {
  const list = MA_NO_SHO_QUOTES;
  if (list.length === 0) return "";
  if (list.length === 1) return list[0];

  let last = -1;
  try {
    const raw = window.localStorage.getItem(LAST_KEY);
    if (raw != null) last = Number.parseInt(raw, 10);
  } catch {
    // ignore
  }

  let index = Math.floor(Math.random() * list.length);
  if (index === last) index = (index + 1) % list.length;

  try {
    window.localStorage.setItem(LAST_KEY, String(index));
  } catch {
    // ignore
  }

  return list[index];
}
